# -*- coding: utf-8 -*-
"""Агент поиска в памяти: решает, нужен ли поиск в фактах и истории пользователя.

Возвращает search-запрос (user_hint) для поиска по эмбеддингам, или None,
если поиск не нужен. Поиск по самой памяти выполняется на Этапе 4 (память);
здесь только решаем — ищем или нет.
"""

import logging
from typing import Optional

logger = logging.getLogger(__name__)

SEARCH_PROMPT = """Ты — координатор поиска в памяти ИИ-компаньона «Элеонора».
Твоя задача: проанализировать последнее сообщение пользователя и решить,
нужно ли искать в его личных фактах и истории диалога.

Поиск идёт по ДВУМ источникам:
1. Личные факты пользователя (имя, отношения, питомцы, работа, хобби, предпочтения)
2. История диалога (прошлые сообщения из старых разговоров)

Если в памяти есть запись, точно соответствующая упомянутой сущности
(кот Жужа, подруга Юля и т.п.) — ОБЯЗАТЕЛЬНО включи её имя в user_hint.

НУЖНО ИСКАТЬ если сообщение связано с:
- Личными фактами: имена, питомцы, работа, семья, хобби, предпочтения
- Прошлыми событиями, о которых пользователь рассказывал ранее
- Личными мнениями, привычками, особенностями
- Вопросами, требующими контекста из предыдущих диалогов
- Упоминанием ЛЮБОЙ личной сущности (даже если пользователь не спрашивает о фактах)

НЕ НУЖНО ИСКАТЬ если:
- Общие знания, наука, абстрактные понятия («как работают чёрные дыры?»)
- Приветствие, small talk («привет», «как дела»)
- Вопросы про код, команды, настройки, технические вопросы
- Текущая тема уже даёт достаточно контекста
- В памяти нет ничего релевантного сообщению

Формат ответа — РОВНО ОДНА СТРОКА, ничего лишнего:

Если поиск нужен:
  user_hint = <короткий поисковый запрос на русском, желательно с именем сущности>

Если поиск не нужен:
  user_hint = no

Примеры:
«кошка Жужа опять нагадила»                -> user_hint = кошка Жужа
«напомни какой у меня график работы»       -> user_hint = график работы пользователя
«как там Жужа поживает?»                   -> user_hint = кошка Жужа
«Юля звонила вчера?»                       -> user_hint = подруга Юля
«привет, как дела?»                        -> user_hint = no
«расскажи про чёрные дыры»                 -> user_hint = no
«как написать функцию на Python»           -> user_hint = no"""


def parse_user_hint(result: Optional[str]) -> Optional[str]:
    """Вытащить значение user_hint из ответа агента.

    Ищем строку вида «user_hint = <значение>». Если значения нет
    или оно «no» — возвращаем None.
    """
    if not result:
        return None
    for raw_line in result.strip().split("\n"):
        line = raw_line.strip()
        if not line or "=" not in line:
            continue
        key, _, value = line.partition("=")
        key = key.strip().lower()
        value = value.strip()
        if not value or value.lower() == "no":
            continue
        if key == "user_hint":
            return value
    return None


def detect(text: str, llm) -> Optional[str]:
    """Решает, нужен ли поиск. Возвращает user_hint или None.

    llm — LLMClient. При любой ошибке безопасно возвращаем None,
    чтобы не ронять пайплайн диалога.
    """
    try:
        raw = llm.generate([{"role": "user", "content": text}], SEARCH_PROMPT)
        hint = parse_user_hint(raw or "")
        if hint:
            logger.info(f"[search_check] нужен поиск: {hint!r}")
        else:
            logger.info("[search_check] поиск не нужен")
        return hint
    except Exception as e:
        logger.warning(f"search_check failed: {e}")
        return None